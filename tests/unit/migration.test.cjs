'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { migrateLegacy } = require('../../src/core/legacy');
const inv = require('../../src/core/inventory');
const weapons = require('../../src/core/weapons');

test('legacy Build 4.5 / 0.9 save migrates characters, inventory and GM data with a precise report', () => {
  const doc = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'fixtures', 'legacy-profiles.json'), 'utf8'));
  const { state: s, report } = migrateLegacy(doc.keys);
  const pc = Object.values(s.characters).find(c => c.name === 'Strelok');
  assert.ok(pc, 'character migrated');
  assert.equal(pc.rank, 3);
  assert.equal(pc.session.hp, 7);
  assert.equal(pc.build.hp, 11);
  assert.equal(pc.session.money, 4250);
  assert.ok(pc.session.conditions.includes('Poisoned'));
  assert.ok(pc.session.conditions.includes('Irradiated'));
  assert.equal(pc.build.skills[0].name, 'Guns'); assert.equal(pc.build.skills[0].spec, 'Rifle'); assert.equal(pc.build.skills[0].level, 14);
  const items = inv.descendants(s, 'char:' + pc.id);
  const akm = items.find(i => i.defId === 'builtin-akm-76239');
  assert.equal(akm.loc.slot, 'primary');
  assert.equal(weapons.roundsAvailable(s, akm), 15, 'loaded magazine kept its rounds (chambered one)');
  const rig = items.find(i => i.defId === 'sample-chest-rig');
  assert.equal(rig.loc.slot, 'rig');
  const m2 = items.find(i => i.loc.p === 'item:' + rig.id);
  assert.deepEqual(m2.rounds, [['t1-ammo-7-62-39mm-hp', 20]], 'ammo matched by name');
  assert.equal(m2.loc.x, 1);
  const charm = items.find(i => i.defId === 'custom-thing');
  assert.equal(charm.loc.g, 'pockets'); assert.equal(charm.loc.x, 1);
  const stash = Object.values(s.stashes).find(x => x.ownerCharId === pc.id);
  const stashItems = inv.descendants(s, 'stash:' + stash.id);
  const sks = stashItems.find(i => i.defId === 't1-weapon-sks');
  assert.deepEqual(sks.rounds, [['t1-ammo-7-62-39mm-fmj', 6]], 'integral magazine rounds folded into the weapon');
  assert.equal(stashItems.filter(i => i.defId === 't1-ammo-7-62-39mm-fmj').reduce((a, i) => a + i.qty, 0), 75, 'loose ammo preserved (split into stacks)');
  assert.equal(s.defs['builtin-akm-76239'].value, 31000, 'user price kept');
  assert.ok(report.notTransferred.some(x => /IndexedDB/.test(x)), 'unreadable image reported');
  assert.ok(report.warnings.some(x => /hands/.test(x)), 'removed hands slot reported');
  assert.ok(s.npcTemplates['tpl-legacy-n1']);
  assert.equal(s.name, 'Zone Campaign');
  const tr = Object.values(s.traders).find(t => t.name === 'Old trader');
  assert.equal(tr.buyMult, 1.2);
  assert.equal(inv.descendants(s, 'trader:' + tr.id).reduce((a, i) => a + i.qty, 0), 4);
  const farm = Object.values(s.stashes).find(x => x.name === 'Farm stash');
  assert.equal(farm.hidden, true);
});
